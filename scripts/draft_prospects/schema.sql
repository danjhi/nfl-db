-- Feeds the DTVC 2027 rookie sub-tab (UPDATE_PLAN.md workstream D). Bio columns are research
-- output, loaded once by the seed below. `value` / `sf_value` are Dan's and are owned by the
-- Google Sheet, pushed via scripts/google-apps-script/draft_prospects_sync.js.
--
-- These are COLLEGE players. They are deliberately NOT in `players` (Sportradar UUID = NFL only),
-- so this table keys on dan_id directly rather than joining through players.dan_id the way
-- dynasty_values does. See the sync script's header for why that distinction matters.

-- ── draft_prospects ──────────────────────────────────────────────────────────
-- One row per prospect per draft class. dan_id is a stable kebab slug carrying the
-- class year (e.g. jeremiah-smith-2027) so a 2028 board can coexist without collision.

CREATE TABLE IF NOT EXISTS draft_prospects (
  dan_id                TEXT PRIMARY KEY,
  draft_year            INT  NOT NULL DEFAULT 2027,
  name                  TEXT NOT NULL,
  position              TEXT NOT NULL CHECK (position IN ('QB', 'RB', 'WR', 'TE')),
  college               TEXT,             -- joins colleges(school); NULL = no 2026 team (see Sorsby)
  class_eligibility     TEXT,
  height_in             INT,
  weight_lb             INT,
  stats_2025            TEXT,
  career_note           TEXT,
  consensus_rank_signal TEXT,             -- e.g. "ATH-U #1, MDD #2, Tank #1"
  scouting_note         TEXT,             -- neutral research note; NOT site copy
  headshot_url          TEXT,
  sources               TEXT,
  sf_rank               INT,              -- research starting sort order, NOT a value
  tier                  TEXT,
  value                 NUMERIC,          -- Dan: 1QB dynasty trade value
  sf_value              NUMERIC,          -- Dan: superflex dynasty trade value
  writeup               TEXT,             -- Dan's own prospect copy (UPDATE_PLAN D1)
  values_updated_at     TIMESTAMPTZ,      -- set by the sheet sync, not by seed loads
  updated_at            TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ── RLS ──────────────────────────────────────────────────────────────────────
-- DTVC's frontend reads this anon, same as news/spotlights.
ALTER TABLE draft_prospects ENABLE ROW LEVEL SECURITY;

CREATE POLICY "anon_select_draft_prospects" ON draft_prospects FOR SELECT USING (true);

-- ── Indexes ──────────────────────────────────────────────────────────────────
CREATE INDEX IF NOT EXISTS idx_draft_prospects_year_rank ON draft_prospects(draft_year, sf_rank);
CREATE INDEX IF NOT EXISTS idx_draft_prospects_position  ON draft_prospects(position);
CREATE INDEX IF NOT EXISTS idx_draft_prospects_college   ON draft_prospects(college);

